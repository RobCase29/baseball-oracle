function tierFor(score: number): ItFactorTier {
  if (score >= 92) return 'icon'
  if (score >= 84) return 'high'
  if (score >= 74) return 'emerging'
  return 'watch'
}

function b(
  teamCode: string,
  playerName: string,
  position: string,
  status: ItFactorStatus,
  score: number,
  confidence: number,
  trajectory: ItFactorTrajectory,
  rationale: string,
  signals: string[],
  sourceIds: string[] = [OFFSEASON, SEASON_REVIEW],
  recheckTriggers?: string[],
): ItFactorCurationEntry {
  const team = IT_FACTOR_EXPECTED_TEAMS.basketball.find(
    (candidate) => candidate.code === teamCode,
  )
  if (!team) throw new Error(`Unknown NBA team ${teamCode}`)
  const teamSlug = normalizeItFactorName(team.name).replaceAll(' ', '-')
  const playerSlug = normalizeItFactorName(playerName).replaceAll(' ', '-')
  return {
    id: `nba-${teamSlug}-${playerSlug}`,
    playerName,
    sport: 'basketball',
    league: 'NBA',
    teamCode,
    teamName: team.name,
    position,
    status,
    score,
    tier: tierFor(score),
    confidence,
    trajectory,
    rationale,
    signals,
    ...(recheckTriggers ? { recheckTriggers } : {}),
    sourceIds,
  }
}

